"use client";

import { useEffect, useRef, useState } from "react";
import { loadDecisions, parsePlan, STATUS_COLOR } from "../lib/decisions";
import { initChrome, initCursor, initGrain, initEnter, wipeNavigate } from "../lib/client";
import LiveEnginePanel from "./LiveEnginePanel";

/* Test bench: run any request, compare with output.csv, add custom test cases.
   Decisions come from /baseline.json — the real engine run generated by
   code/tools/gen_baseline.py (double-run verified deterministic). */

const fmt = (n) => Number(n).toLocaleString("en-US", { maximumFractionDigits: 2 });
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
}[c]));

function scoreCustom(c, byId) {
  const row = byId.get(c.id);
  const results = [];
  if (!row) {
    results.push(["exists", false, "unknown request id"]);
    return { ok: false, results };
  }
  results.push(["exists", true, "known request"]);
  const affordable = row.status !== "not_affordable";
  if (c.expect === "affordable") results.push(["verdict", affordable, `engine says ${row.status}`]);
  if (c.expect === "full_now") results.push(["verdict", row.status === "affordable_now", `engine says ${row.status}`]);
  if (c.expect === "not_affordable") results.push(["verdict", row.status === "not_affordable", `engine says ${row.status}`]);
  if (c.expect === "any") results.push(["verdict", true, row.status]);
  if (c.floor === "yes") results.push(["floor", row.explanation.includes("minimum") || row.status === "affordable_now", "explanation references the protected minimum"]);
  return { ok: results.every(([, pass]) => pass), results };
}

export default function TestBench() {
  const rootRef = useRef(null);
  const uidRef = useRef(0);
  const [data, setData] = useState(null);
  const [current, setCurrent] = useState(null);
  const [cmpRow, setCmpRow] = useState(null);
  const [custom, setCustom] = useState([]);
  const [pick, setPick] = useState("");
  const [compare, setCompare] = useState(true);
  const [cf, setCf] = useState({ id: "", amount: "", expect: "any", floor: "yes" });

  useEffect(() => {
    initChrome();
    initCursor();
    initGrain();
    initEnter();
    Promise.all([
      fetch("/baseline.json").then((r) => (r.ok ? r.json() : Promise.reject(new Error("baseline.json missing")))),
      loadDecisions(),
    ]).then(([baseline, output]) => {
      const byId = new Map(baseline.map((row) => [row.request_id, row]));
      const outputIndex = new Map();
      if (output) {
        output.decisions.forEach((d) => outputIndex.set(d.request_id, {
          affordability_status: d.status,
          recommended_payment_method: d.method,
          amount_safe_to_pay: d.amount,
          payment_plan: d.plan.map((p) => `${p.date}:${p.amount}`).join("|") || "none",
          earliest_date_for_full_payment: d.earliest || "",
          decision_explanation: d.explanation,
        }));
      }
      setData({ byId, outputIndex, ids: [...byId.keys()].sort() });
      const params = new URLSearchParams(location.search);
      const wantCmp = params.get("cmp") !== "0";
      setCompare(wantCmp);
      if (params.get("cases")) {
        const restored = [];
        params.get("cases").split(",").forEach((tok) => {
          const [cid, expect = "any", floor = "yes"] = tok.split("~");
          if (cid) restored.push({ uid: "case_" + (++uidRef.current), id: cid, expect, floor });
        });
        setCustom(restored);
      }
      const initId = params.get("id") || "request_30";
      setCurrent(byId.get(initId) || null);
      setCmpRow(wantCmp ? outputIndex.get(initId) || null : null);
    }).catch(() => setData({ byId: new Map(), outputIndex: new Map(), ids: [] }));
  }, []);

  /* URL state: ?id=request_XX&cmp=0&cases=request_28~not_affordable~yes — shareable runs. */
  const syncCasesURL = (next) => {
    const p = new URLSearchParams(location.search);
    if (next.length) p.set("cases", next.map((c) => `${c.id}~${c.expect}~${c.floor}`).join(","));
    else p.delete("cases");
    const qs = p.toString();
    history.replaceState(null, "", location.pathname + (qs ? "?" + qs : ""));
  };

  const run = (id) => {
    if (!data) return;
    const row = data.byId.get(id.trim());
    if (!row) { setCurrent(null); setCmpRow(null); return; }
    setCurrent(row);
    setCmpRow(compare ? data.outputIndex.get(row.request_id) || null : null);
    const p = new URLSearchParams(location.search);
    p.set("id", row.request_id);
    if (compare) p.delete("cmp"); else p.set("cmp", "0");
    const qs = p.toString();
    history.replaceState(null, "", location.pathname + (qs ? "?" + qs : ""));
  };

  const addCase = () => {
    if (!cf.id.trim()) return;
    const next = [...custom, { ...cf, id: cf.id.trim(), uid: "case_" + (++uidRef.current) }];
    setCustom(next);
    syncCasesURL(next);
    setCf({ id: "", amount: "", expect: "any", floor: "yes" });
  };

  const planRows = current && current.plan !== "none"
    ? parsePlan(current.plan)
    : [];

  return (
    <main id="stage">
      <div className="testbench">
        <div className="tb-head">
          <div className="res-kicker">TEST BENCH — ENGINE INVITATION</div>
          <h1 className="res-title">RUN THE AGENT.<br />CHECK ITS WORK.</h1>
          <p className="res-sub">Every decision below is the real deterministic engine output
          (double-run verified). Compare it against the submitted output.csv, or add your
          own custom test cases and score them with the same invariants the validator uses.</p>
        </div>

        <div className="tb-runner res-block">
          <h2>RUN A REQUEST</h2>
          <div className="tb-controls">
            <input
              list="tbList"
              placeholder="TYPE A REQUEST ID (e.g. request_30)"
              value={pick}
              onChange={(e) => setPick(e.target.value)}
              onKeyDown={(e) => { if (e.key === "Enter") run(pick); }}
            />
            <datalist id="tbList">
              {(data ? data.ids : []).map((id) => <option key={id} value={id} />)}
            </datalist>
            <button className="hot" onClick={() => run(pick)}>RUN &gt;</button>
            <button className="hot" onClick={() => {
              if (!data || !data.ids.length) return;
              const id = data.ids[Math.floor(Math.random() * data.ids.length)];
              setPick(id);
              run(id);
            }}>RANDOM</button>
            <label className="tb-toggle">
              <input type="checkbox" checked={compare} onChange={(e) => {
                setCompare(e.target.checked);
                if (current) setCmpRow(e.target.checked ? data.outputIndex.get(current.request_id) || null : null);
                const p = new URLSearchParams(location.search);
                if (e.target.checked) p.delete("cmp"); else p.set("cmp", "0");
                const qs = p.toString();
                history.replaceState(null, "", location.pathname + (qs ? "?" + qs : ""));
              }} /> COMPARE WITH OUTPUT.CSV
            </label>
          </div>
          <div className="tb-out">
            {!data ? <div className="tb-hint">LOADING ENGINE BASELINE…</div>
              : !current ? <div className="tb-hint">NO SUCH REQUEST — PICK ONE FROM THE LIST.</div>
              : (
                <div className="tb-decision">
                  <div className="dec-top">
                    <b>{current.request_id}</b>
                    <span className="dec-status" style={{ "--sc": STATUS_COLOR[current.status] || "#fff" }}>{current.status}</span>
                  </div>
                  <div className="dec-facts">
                    <div><i>AMOUNT SAFE TO PAY</i><span className="ev-amt">{fmt(current.amount)}</span></div>
                    <div><i>METHOD</i><span>{current.method}</span></div>
                    <div><i>EARLIEST FULL PAYMENT</i><span>{current.earliest || "—"}</span></div>
                    <div><i>SPENDING CHANGES</i><span>{esc(current.spending)}</span></div>
                  </div>
                  <table className="dec-plan">
                    <thead><tr><th>#</th><th>DATE</th><th>AMOUNT</th></tr></thead>
                    <tbody>
                      {planRows.length
                        ? planRows.map((p, i) => (
                            <tr key={i}><td>{i + 1}</td><td>{p.date}</td><td className="ev-amt">{fmt(p.amount)}</td></tr>
                          ))
                        : <tr><td colSpan={3} className="dec-none">none</td></tr>}
                    </tbody>
                  </table>
                  <div className="dec-expl-full"><i>DECISION EXPLANATION (ENGINE OUTPUT)</i>{esc(current.explanation)}</div>
                  {cmpRow && (() => {
                    const checks = [
                      ["status", current.status === cmpRow.affordability_status],
                      ["method", current.method === cmpRow.recommended_payment_method],
                      ["amount", Number(current.amount) === Number(cmpRow.amount_safe_to_pay)],
                      ["plan", current.plan === cmpRow.payment_plan],
                      ["earliest", (current.earliest || "") === (cmpRow.earliest_date_for_full_payment || "")],
                    ];
                    const ok = checks.every(([, pass]) => pass);
                    return (
                      <div className={"tb-cmp " + (ok ? "ok" : "diff")}>
                        <b>{ok ? "OUTPUT.CSV — MATCH" : "OUTPUT.CSV — DIFFERS"}</b>
                        <ul>{checks.map(([k, pass]) => <li key={k} className={pass ? "pass" : "fail"}>{k}</li>)}</ul>
                        <pre>{esc(cmpRow.decision_explanation)}</pre>
                      </div>
                    );
                  })()}
                </div>
              )}
          </div>
        </div>

        <LiveEnginePanel />

        <div className="tb-custom res-block">
          <h2>CUSTOM TEST CASES</h2>
          <div className="tb-form">
            <div className="tb-field"><i>REQUEST ID</i>
              <input value={cf.id} placeholder="request_999" onChange={(e) => setCf({ ...cf, id: e.target.value })} />
            </div>
            <div className="tb-field"><i>REQUESTED AMOUNT</i>
              <input type="number" min="0" step="0.01" placeholder="5000" value={cf.amount} onChange={(e) => setCf({ ...cf, amount: e.target.value })} />
            </div>
            <div className="tb-field"><i>EXPECTS</i>
              <select value={cf.expect} onChange={(e) => setCf({ ...cf, expect: e.target.value })}>
                <option value="any">any verdict</option>
                <option value="affordable">affordable somehow</option>
                <option value="full_now">full payment now</option>
                <option value="not_affordable">not affordable</option>
              </select>
            </div>
            <div className="tb-field"><i>FLOOR HOLDS?</i>
              <select value={cf.floor} onChange={(e) => setCf({ ...cf, floor: e.target.value })}>
                <option value="yes">must hold</option>
                <option value="no">n/a</option>
              </select>
            </div>
            <button className="hot" onClick={addCase}>+ ADD CASE</button>
          </div>
          <div className="tb-cases">
            {!custom.length && (
              <div className="tb-hint">NO CUSTOM CASES YET. EXAMPLE: EXPECT request_28 TO BE not_affordable WITH THE FLOOR HOLDING.</div>
            )}
            {custom.map((c, i) => {
              const s = data ? scoreCustom(c, data.byId) : { ok: false, results: [] };
              return (
                <div key={c.uid} className={"tb-case " + (s.ok ? "ok" : "diff")}>
                  <div className="dec-top">
                    <b>{esc(c.id)}</b>
                    <span className={"tb-badge " + (s.ok ? "pass" : "fail")}>{s.ok ? "PASS" : "FAIL"}</span>
                    <button className="tb-del" onClick={() => { const next = custom.filter((_, k) => k !== i); setCustom(next); syncCasesURL(next); }}>×</button>
                  </div>
                  <div className="tb-case-meta">expect {esc(c.expect)} · floor {esc(c.floor)}{c.amount ? ` · amount ${fmt(c.amount)}` : ""}</div>
                  <ul className="tb-checks">
                    {s.results.map(([k, pass, note], j) => (
                      <li key={j} className={pass ? "pass" : "fail"}><i>{k}</i>{esc(note)}</li>
                    ))}
                  </ul>
                </div>
              );
            })}
          </div>
        </div>
      </div>
    </main>
  );
}
